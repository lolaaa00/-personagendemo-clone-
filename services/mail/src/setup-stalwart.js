"use strict";

const crypto = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");
const { execSync } = require("node:child_process");

const MAIL_DOMAIN = process.env.MAIL_DOMAIN || "mail.personagen.com";
const DKIM_SELECTOR = process.env.DKIM_SELECTOR || "personagen";
const STALWART_DATA = process.env.STALWART_DATA_DIR || "/data/stalwart";
const DKIM_DIR = "/data/dkim";
const ADMIN_USER = process.env.MAIL_ADMIN_USER || "admin";
const ADMIN_PASS = process.env.MAIL_ADMIN_PASS || "";

function log(level, msg, extra = {}) {
  console.log(
    JSON.stringify({
      level,
      msg,
      service: "mail-setup",
      ...extra,
      ts: new Date().toISOString(),
    })
  );
}

async function setup() {
  log("info", "Starting Stalwart mail server configuration", { domain: MAIL_DOMAIN });

  /* ── Ensure directories ───────────────────── */
  const dirs = [
    STALWART_DATA,
    path.join(STALWART_DATA, "etc"),
    path.join(STALWART_DATA, "data"),
    path.join(STALWART_DATA, "queue"),
    path.join(STALWART_DATA, "logs"),
    DKIM_DIR,
  ];

  for (const dir of dirs) {
    fs.mkdirSync(dir, { recursive: true });
  }

  /* ── Generate DKIM keys if they don't exist ── */
  const privateKeyPath = path.join(DKIM_DIR, "private.pem");
  const publicKeyPath = path.join(DKIM_DIR, "public.pem");

  if (!fs.existsSync(privateKeyPath)) {
    log("info", "Generating DKIM keypair");

    try {
      execSync(`openssl genrsa -out "${privateKeyPath}" 2048`, { stdio: "pipe" });
      execSync(`openssl rsa -in "${privateKeyPath}" -pubout -out "${publicKeyPath}"`, {
        stdio: "pipe",
      });
      fs.chmodSync(privateKeyPath, 0o600);
      fs.chmodSync(publicKeyPath, 0o644);
      log("info", "DKIM keypair generated successfully");
    } catch (err) {
      log("error", "DKIM key generation failed", { error: err.message });
      throw err;
    }
  } else {
    log("info", "DKIM keys already exist");
  }

  /* ── Output DNS records ───────────────────── */
  const publicKey = fs.readFileSync(publicKeyPath, "utf8");
  const dkimDnsValue = publicKey
    .replace(/-----BEGIN PUBLIC KEY-----/, "")
    .replace(/-----END PUBLIC KEY-----/, "")
    .replace(/\s+/g, "");

  log("info", "Required DNS records", {
    mx: { type: "MX", name: "@", value: MAIL_DOMAIN, priority: 10 },
    spf: {
      type: "TXT",
      name: "@",
      value: `v=spf1 mx a:${MAIL_DOMAIN} -all`,
    },
    dkim: {
      type: "TXT",
      name: `${DKIM_SELECTOR}._domainkey`,
      value: `v=DKIM1; k=rsa; p=${dkimDnsValue}`,
    },
    dmarc: {
      type: "TXT",
      name: "_dmarc",
      value: `v=DMARC1; p=quarantine; rua=mailto:admin@${MAIL_DOMAIN}; pct=100`,
    },
  });

  /* ── Write Stalwart configuration ─────────── */
  const stalwartConfig = buildStalwartConfig();
  const configPath = path.join(STALWART_DATA, "etc", "config.toml");
  fs.writeFileSync(configPath, stalwartConfig, "utf8");
  log("info", "Stalwart configuration written", { path: configPath });

  /* ── Create admin inbox ───────────────────── */
  if (ADMIN_PASS) {
    const accountsDir = path.join(STALWART_DATA, "data", "accounts");
    fs.mkdirSync(accountsDir, { recursive: true });

    const adminAccountFile = path.join(accountsDir, `${ADMIN_USER}.json`);
    const hashedPass = crypto
      .createHash("sha256")
      .update(ADMIN_PASS)
      .digest("hex");

    const adminAccount = {
      username: ADMIN_USER,
      password: hashedPass,
      email: `${ADMIN_USER}@${MAIL_DOMAIN}`,
      role: "admin",
      quota: 0,
      created: new Date().toISOString(),
    };

    fs.writeFileSync(adminAccountFile, JSON.stringify(adminAccount, null, 2), "utf8");
    log("info", "Admin inbox created", {
      user: ADMIN_USER,
      email: `${ADMIN_USER}@${MAIL_DOMAIN}`,
    });
  } else {
    log("warn", "MAIL_ADMIN_PASS not set — skipping admin inbox creation");
  }

  log("info", "Stalwart setup complete");
}

function buildStalwartConfig() {
  return `# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
# Stalwart Mail Server — PersonaGen Configuration
# Auto-generated by setup-stalwart.js
# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

[server]
hostname = "${MAIL_DOMAIN}"
max-connections = 1024

[server.listener.smtp]
bind = ["0.0.0.0:25"]
protocol = "smtp"

[server.listener.submission]
bind = ["0.0.0.0:587"]
protocol = "smtp"

[server.listener.imaps]
bind = ["0.0.0.0:993"]
protocol = "imap"

[server.listener.http]
bind = ["0.0.0.0:8443"]
protocol = "http"

[storage]
data = "${STALWART_DATA}/data"
blob = "${STALWART_DATA}/data/blobs"

[queue]
path = "${STALWART_DATA}/queue"

[directory."local"]
type = "internal"
store = "local"

[auth]
mechanisms = ["PLAIN", "LOGIN"]

[signature.dkim."${DKIM_SELECTOR}"]
private-key = "file://${DKIM_DIR}/private.pem"
domain = "${MAIL_DOMAIN}"
selector = "${DKIM_SELECTOR}"
headers = ["From", "To", "Date", "Subject", "Message-ID"]
algorithm = "rsa-sha256"
canonicalization = "relaxed/relaxed"
expire = "7d"

[session.rcpt]
max-recipients = 25
relay = true

[session.data]
max-message-size = 26214400
pipe."inbox-deliver" = "node /app/src/inbox-deliver.js"

[report.dmarc]
send = "admin@${MAIL_DOMAIN}"

[report.tls]
send = "admin@${MAIL_DOMAIN}"
`;
}

setup().catch((err) => {
  log("fatal", "Setup failed", { error: err.message, stack: err.stack });
  process.exit(1);
});
